    public static void refreshDataMotor(String w) {
        try {
            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            for (int i = model.getRowCount() - 1; i >= 0; i--) {
                model.removeRow(i);
            }

            Connection K = Koneksi.Go();
            String Q = "SELECT * FROM tabel_motor" + w;
            Statement S = K.createStatement();
            ResultSet R = S.executeQuery(Q);
            while (R.next()) {
                int id = R.getInt("id_motor");
                String merk = R.getString("merk");
                String tipe = R.getString("tipe");
                String tahun = R.getString("tahun");
                String warna = R.getString("warna");
                String harga = R.getString("harga");
                String stok = R.getString("stok");
                Object[] datamotor = {id, merk, tipe, tahun, warna, harga, stok};
                model.addRow(datamotor);
            }

        } catch (Exception e) {
            System.out.println("Error: " + e.getMessage());

        }
    }

    private void searchDataMotor() {
        String key = srcMotor.getText();
        String where = " WHERE "
                + "id_motor LIKE '%" + key + "%' OR "
                + "merk LIKE '%" + key + "%' OR "
                + "tipe LIKE '%" + key + "%' OR "
                + "tahun LIKE '%" + key + "%' OR "
                + "warna LIKE '%" + key + "%' OR "
                + "harga LIKE '%" + key + "%' OR "
                + "stok LIKE '%" + key + "%'";
        refreshDataMotor(where);
    }

    // Method untuk membuat Kode Transaksi Otomatis (Contoh: TRX001)
    private void otomatisKodeTransaksi() {
        try {
            java.sql.Connection conn = (java.sql.Connection) Bmj.util.Koneksi.Go();
            java.sql.Statement stm = conn.createStatement();

            // Ambil id_transaksi terakhir, urutkan dari yang terbesar
            String sql = "SELECT id_transaksi FROM transaksi ORDER BY id_transaksi DESC LIMIT 1";
            java.sql.ResultSet res = stm.executeQuery(sql);

            if (res.next()) {
                String id = res.getString("id_transaksi");
                // Misal format ID di database adalah "TRX001"
                // Kita ambil angkanya saja (mulai indeks ke-3)
                int nomor = Integer.parseInt(id.substring(3)) + 1;

                // Format ulang menjadi TRX + 3 digit angka (001, 002, dst)
                String kodeBaru = "TRX" + String.format("%03d", nomor);
                inpKode.setText(kodeBaru); // Pastikan nama variabel textfield kamu sesuai
            } else {
                // Jika belum ada data sama sekali
                inpKode.setText("TRX001");
            }
        } catch (Exception e) {
            System.out.println("Error Kode Otomatis: " + e.getMessage());
            // Fallback jika error
            inpKode.setText("TRX001");
        }
    }

    private void hitungTotalBelanja() {
        int total = 0;
        for (int i = 0; i < jTable2.getRowCount(); i++) {
            // Ambil angka dari kolom Subtotal (misal kolom index 3)
            int sub = Integer.parseInt(jTable2.getValueAt(i, 3).toString());
            total += sub;
        }
        inpTotal.setText(String.valueOf(total)); // txtTotal adalah nama field Total di bawah
    }

