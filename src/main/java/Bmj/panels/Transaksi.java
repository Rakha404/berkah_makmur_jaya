    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        int barisAtas = jTable1.getSelectedRow();
        if (barisAtas == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih motor dulu di tabel atas!");
            return;
        }

        if (srcJumlah.getText().equals("")) { // srcJumlah sesuaikan dengan nama variabelmu
            javax.swing.JOptionPane.showMessageDialog(this, "Isi jumlah barang!");
            return;
        }
        String id_transaksi = inpKode.getText();
        String namaPegawai = "Admin";
        String idPelanggan = "PLG-" + (new java.util.Random().nextInt(9000) + 1000);

        String merk = jTable1.getValueAt(barisAtas, 1).toString();

        // Ambil Harga dari Tabel Atas (Kolom ke-5 / indeks 5)
        String hargaStr = jTable1.getValueAt(barisAtas, 5).toString();
        // Bersihkan titik/koma (misal 15.000.000 jadi 15000000)
        long harga = Long.parseLong(hargaStr.replace(".", "").replace(",", ""));
        int jumlah = Integer.parseInt(srcJumlah.getText());
        long total_harga = harga * jumlah;

        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable2.getModel();

        model.addRow(new Object[]{
            id_transaksi,
            namaPegawai,
            idPelanggan,
            merk,
            harga,
            jumlah,
            total_harga
        });
        hitungTotalBelanja();

        try {
            // Ambil angka dari kode sekarang (misal "TRX001" diambil "001")
            // Asumsi formatnya selalu 3 huruf depan diikuti angka
            // Ambil teksnya dulu (.getText()), baru dipotong (.substring)
            String angkaSaja = inpKode.getText().substring(3);
            int urutanBaru = Integer.parseInt(angkaSaja) + 1;

            // Format balik menjadi TRX + 3 digit angka (misal TRX002)
            String kodeBaru = "TRX" + String.format("%03d", urutanBaru);

            // Pasang kode baru ke textfield agar siap untuk barang berikutnya
            inpKode.setText(kodeBaru);

        } catch (Exception e) {
            // Jika format kode kamu bukan TRX... (misal manual ketik "aa1")
            // Maka biarkan saja, atau buat logika lain.
            System.out.println("Gagal auto increment kode: " + e.getMessage());
        }

    }//GEN-LAST:event_jButton1ActionPerformed


